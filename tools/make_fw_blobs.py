"""gpu-unlock-rt · generate driver/gu_fw_blobs.h from the five firmware assets.

Four small assets are embedded as byte arrays (booter, v67, gsp_boot,
gsp_boot_desc). The 84 MB GSP image is NOT embedded as a flat buffer: the
driver reads it at transaction time from \SystemRoot\System32\drivers\GuRtGsp.bin
(gu_gsp.c), using the ELF section spans extracted here and hash-bound below —
the same request_firmware/runtime split upstream uses, with spans replacing
in-memory ELF parsing.

Usage: python make_fw_blobs.py <asset_dir> <out_header>
"""
import hashlib
import struct
import sys
from pathlib import Path

EMBED = [
    ("GuFwBooter", "booter_load_ga102.bin"),
    ("GuFwV67", "v67-ga102-610.43.03.bin"),
    ("GuFwBoot", "gsp_boot_ga102.bin"),
    ("GuFwBootDesc", "gsp_boot_desc_ga102.bin"),
]
GSP = "gsp_ga10x.bin"
GSP_PATH = "\\SystemRoot\\System32\\drivers\\GuRtGsp.bin"


def c_array(name: str, data: bytes) -> str:
    lines = [f"const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def elf_spans(path: Path) -> dict:
    """Minimal ELF64 section scan: name -> (offset, size)."""
    spans = {}
    with path.open("rb") as f:
        eh = f.read(64)
        if eh[:4] != b"\x7fELF" or eh[4] != 2:
            raise ValueError("not ELF64")
        shoff = struct.unpack_from("<Q", eh, 0x28)[0]
        shentsize, shnum = struct.unpack_from("<HH", eh, 0x3A)
        e_shstrndx = struct.unpack_from("<H", eh, 0x3E)[0]
        f.seek(shoff)
        sh = f.read(shentsize * shnum)

        def shdr(i):
            b = sh[i * shentsize:(i + 1) * shentsize]
            nameoff, typ = struct.unpack_from("<II", b, 0)
            off, size = struct.unpack_from("<QQ", b, 24)
            return nameoff, typ, off, size

        _, _, stroff, strsize = shdr(e_shstrndx)
        f.seek(stroff)
        strtab = f.read(strsize)
        for i in range(shnum):
            nameoff, _, off, size = shdr(i)
            end = strtab.find(b"\0", nameoff)
            name = strtab[nameoff:end].decode()
            if name:
                spans[name] = (off, size)
    return spans


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    asset_dir, out_path = Path(sys.argv[1]), Path(sys.argv[2])

    parts = [
        "// SPDX-License-Identifier: GPL-2.0-only",
        "// GENERATED by gpu-unlock-rt/tools/make_fw_blobs.py - do not edit.",
        "// NVIDIA firmware assets remain under NVIDIA's terms (upstream",
        "// NOTICE.md); this header is a local build artifact, do not commit it.",
        "#ifndef GU_FW_BLOBS_H",
        "#define GU_FW_BLOBS_H",
        "",
    ]
    for cname, fname in EMBED:
        p = asset_dir / fname
        if not p.is_file():
            print(f"missing asset: {p}", file=sys.stderr)
            return 1
        data = p.read_bytes()
        parts.append(c_array(cname, data))
        parts.append(f"#define {cname}Size ((unsigned long){len(data)})")
        parts.append(f"// sha256 {fname}: {hashlib.sha256(data).hexdigest()}")
        parts.append("")

    gsp = asset_dir / GSP
    if not gsp.is_file():
        print(f"missing asset: {gsp}", file=sys.stderr)
        return 1
    spans = elf_spans(gsp)
    for sec in (".fwimage", ".fwsignature_ga10x"):
        if sec not in spans:
            print(f"missing ELF section {sec} in {GSP}", file=sys.stderr)
            return 1
    img_off, img_size = spans[".fwimage"]
    sig_off, sig_size = spans[".fwsignature_ga10x"]
    parts.append('#define GuGspBinPath L"' + GSP_PATH.replace(chr(92), chr(92) * 2) + '"')
    parts.append(f"// sha256 {GSP}: {hashlib.sha256(gsp.read_bytes()).hexdigest()}")
    parts.append(f"#define GuGspFileSize ((unsigned long long){gsp.stat().st_size})")
    parts.append(f"#define GuGspImageOffset ((unsigned long long){img_off})")
    parts.append(f"#define GuGspImageSize ((unsigned long long){img_size})")
    parts.append(f"#define GuGspSigOffset ((unsigned long long){sig_off})")
    parts.append(f"#define GuGspSigSize ((unsigned long long){sig_size})")
    parts.append("")
    parts.append("#endif // GU_FW_BLOBS_H")
    out_path.write_text("\n".join(parts), encoding="ascii")
    print(f"wrote {out_path} ({out_path.stat().st_size} bytes) "
          f"image={img_size:#x}@{img_off:#x} sig={sig_size}@{sig_off:#x}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
