"""gpu-unlock-rt · generate driver/gu_fw_blobs.h from the five firmware assets.

The Linux module loads these via request_firmware (u610:27-31). The Windows
port pins them at build time instead: no kernel file I/O, assets tied to the
binary by construction. Obtain the assets exactly as upstream pins them:

    cd ../gpu-unlock/firmware
    python fetch_artifacts.py          # hash-pinned NVIDIA/CachyOS downloads
    python generate_v67.py             # -> v67-ga102-610.43.03.bin
    python extract_boot_assets.py      # -> booter_load/gsp_boot/gsp_boot_desc

This tool records each blob's SHA-256 in the header so a build can be audited
against the upstream artifact set without trusting the generator.

Usage: python make_fw_blobs.py <asset_dir> <out_header>
"""
import hashlib
import sys
from pathlib import Path

BLOBS = [
    ("GuFwBooter", "booter_load_ga102.bin"),
    ("GuFwV67", "v67-ga102-610.43.03.bin"),
    ("GuFwGsp", "gsp_ga10x.bin"),
    ("GuFwBoot", "gsp_boot_ga102.bin"),
    ("GuFwBootDesc", "gsp_boot_desc_ga102.bin"),
]


def c_array(name: str, data: bytes) -> str:
    lines = [f"const unsigned char {name}_data[] = {{"]
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    asset_dir, out_path = Path(sys.argv[1]), Path(sys.argv[2])

    parts = [
        "// SPDX-License-Identifier: GPL-2.0-only",
        "// GENERATED by gpu-unlock-rt/tools/make_fw_blobs.py — do not edit.",
        "// Firmware assets remain under NVIDIA's terms (upstream NOTICE.md);",
        "// this header is a local build artifact and must not be redistributed.",
        "#ifndef GU_FW_BLOBS_H",
        "#define GU_FW_BLOBS_H",
        "",
    ]
    for cname, fname in BLOBS:
        p = asset_dir / fname
        if not p.is_file():
            print(f"missing asset: {p}", file=sys.stderr)
            return 1
        data = p.read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        parts.append(c_array(cname, data))
        parts.append(f"#define {cname}Size ((unsigned long){len(data)})")
        parts.append(f"// sha256 {fname}: {digest}")
        parts.append("")
    parts.append("#endif // GU_FW_BLOBS_H")
    out_path.write_text("\n".join(parts), encoding="ascii")
    print(f"wrote {out_path} ({out_path.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
